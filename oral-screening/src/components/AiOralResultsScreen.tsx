"use client";

import React, { useState } from "react";
import TopNavbar from "./TopNavbar";
import Button from "./Button";
import ImagePreview from "./ImagePreview";
import type { CapturedImageRecord } from "@/lib/types";

interface Props {
  captures: CapturedImageRecord[];
  onBack: () => void;
  onNext: () => void;
}

const AiOralResultsScreen = (props: Props) => {
  const { captures, onBack, onNext } = props;
  const [previewImageUrl, setPreviewImageUrl] = useState<string | null>(null);

  return (
    <div className="relative flex h-[800px] w-[360px] flex-col overflow-hidden bg-surface-primary shadow-xl">
      <TopNavbar label="Oral" sublabel="Screening" onBack={onBack} />

      <div className="bg-states-error-light px-md py-md">
        <p className="text-title-md text-brand-primary-dark">
          AI Oral Screening Results
        </p>
      </div>

      <div className="no-scrollbar flex-1 overflow-y-auto px-4 pb-24 pt-4">
        <p className="text-body-md text-brand-primary-dark">
          Image-wise AI Assessment
        </p>

        <div className="mt-4 flex flex-col gap-4">
          {captures.map((img, index) => (
            <div key={img.id} className="flex flex-col gap-2">
              <button
                type="button"
                onClick={() => setPreviewImageUrl(img.imageUrl)}
                className="relative h-32 w-full overflow-hidden rounded-lg"
              >
                <img
                  src={img.imageUrl}
                  alt={img.siteName}
                  className="size-full object-cover"
                />
                <div className="pointer-events-none absolute inset-x-0 top-0 h-[73px] bg-gradient-to-b from-black/60 to-transparent" />
                <span className="absolute left-2 top-2 flex size-6 items-center justify-center rounded-full bg-brand-neutral text-label-sm text-black">
                  {index + 1}
                </span>
              </button>
              <div className="flex flex-col gap-2">
                <p className="text-body-md text-text-secondary">AI Verdicts</p>
                <p className="text-body-sm text-text-primary">
                  Some verdict generated by the AI. The text color will
                  indicate the severity of the verdict.
                </p>
              </div>
            </div>
          ))}
        </div>
      </div>

      <div className="flex items-center justify-between gap-2 border-t border-border bg-surface-primary px-4 py-4">
        <Button label="Back" variant="secondary" onClick={onBack} />
        <Button label="Next" variant="primary" onClick={onNext} />
      </div>

      {previewImageUrl && (
        <ImagePreview
          imageUrl={previewImageUrl}
          onClose={() => setPreviewImageUrl(null)}
        />
      )}
    </div>
  );
};

export default AiOralResultsScreen;
